function makeSampleSeries({ base = 30.24, drift = -0.08, noise = 0.02 } = {}) {
  const points: Reading[] = [];
  for (let i = 0; i < 24; i++) {
    const trend = (drift / 23) * i;
    const wobble = Math.sin(i / 3) * (noise / 2) + Math.cos(i / 5) * (noise / 3);
    const p = base + trend + wobble;
    points.push({
      t: i,
      label: formatTimeLabel(i - 23),
      pressure_inhg: round(p, 3),
      temp_f: round(33 + Math.sin(i / 4) * 10, 1),
      humidity: round(55 + Math.cos(i / 6) * 10, 0),
      wind_mph: round(3 + Math.max(0, Math.sin(i / 4) * 5), 0),
    });
  }
  return points;
}

function calcDeltas(series: Reading[]) {
  const last = series[series.length - 1];
  const getNHoursAgo = (n: number) => series[Math.max(0, series.length - 1 - n)];
  const pNow = last.pressure_inhg;

  const p1 = getNHoursAgo(1).pressure_inhg;
  const p3 = getNHoursAgo(3).pressure_inhg;
  const p6 = getNHoursAgo(6).pressure_inhg;
  const p24 = getNHoursAgo(23).pressure_inhg;

  const d1 = pNow - p1;
  const d3 = pNow - p3;
  const d6 = pNow - p6;
  const d24 = pNow - p24;

  const roc1 = d1 / 1;
  const roc3 = d3 / 3;

  return { pNow, d1, d3, d6, d24, roc1, roc3 };
}

type TrendTone = "ok" | "warn" | "danger";

function classifyTrend(rocInHgPerHr: number): { label: string; tone: TrendTone } {
  const r = rocInHgPerHr;
  const abs = Math.abs(r);

  if (abs < 0.005) return { label: "Stable", tone: "ok" };
  if (r < 0) {
    if (abs < 0.02) return { label: "Slowly Falling", tone: "warn" };
    return { label: "Rapid Drop", tone: "danger" };
  }
  if (abs < 0.02) return { label: "Slowly Rising", tone: "warn" };
  return { label: "Rapid Rise", tone: "danger" };
}

function riskFromDeltas({
  d3,
  d6,
  roc3,
}: {
  d3: number;
  d6: number;
  roc3: number;
}): { label: string; tone: TrendTone } {
  const a3 = Math.abs(d3);
  const a6 = Math.abs(d6);
  const ar = Math.abs(roc3);

  let score = 0;
  if (a3 >= 0.08) score += 2;
  else if (a3 >= 0.05) score += 1;

  if (a6 >= 0.12) score += 2;
  else if (a6 >= 0.08) score += 1;

  if (ar >= 0.03) score += 2;
  else if (ar >= 0.02) score += 1;

  if (score <= 1) return { label: "Low", tone: "ok" };
  if (score <= 3) return { label: "Elevated", tone: "warn" };
  return { label: "High", tone: "danger" };
}

function toneClasses(tone: TrendTone) {
  if (tone === "danger") return "bg-red-600/90 text-white";
  if (tone === "warn") return "bg-yellow-500/90 text-black";
  return "bg-emerald-600/90 text-white";
}

function softToneBorder(tone: TrendTone) {
  if (tone === "danger") return "border-red-500/30";
  if (tone === "warn") return "border-yellow-500/30";
  return "border-emerald-500/30";
}

