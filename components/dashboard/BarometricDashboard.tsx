function makeEventId() {
  try {
    if (typeof crypto !== "undefined" && "randomUUID" in crypto) {
      return crypto.randomUUID();
    }
  } catch {}
  return `evt_${Date.now()}_${Math.random().toString(36).slice(2, 8)}`;
}

