function fmtDualPressure(inHg: number) {
  return `${round(inHg, 2)} inHg (${round(inHgToHpa(inHg), 1)} hPa)`;
}

function fmtDualTemp(f: number) {
  return `${round(f, 1)} F (${round(fToC(f), 1)} C)`;
}

function fmtDualDelta(inHgDelta: number) {
  const sign = inHgDelta >= 0 ? "+" : "";
  const inTxt = `${sign}${round(inHgDelta, 2)} in`;
  const hpaTxt = `${sign}${round(inHgToHpa(inHgDelta), 1)} hPa`;
  return `${inTxt} (${hpaTxt})`;
}

function fmtDualRate(inHgPerHr: number) {
  const sign = inHgPerHr >= 0 ? "+" : "";
  const inTxt = `${sign}${round(inHgPerHr, 3)} in/hr`;
  const hpaTxt = `${sign}${round(inHgToHpa(inHgPerHr), 2)} hPa/hr`;
  return `${inTxt} (${hpaTxt})`;
}

